import { chromium, devices } from 'playwright'
const S = process.argv[2]
const b = await chromium.launch()
for (const tema of ['light', 'dark']) {
  const ctx = await b.newContext({ ...devices['Pixel 7'], colorScheme: tema })
  const p = await ctx.newPage()
  await p.goto('http://localhost:4181/')
  await p.screenshot({ path: `${S}/v-${tema}-acceso.png`, fullPage: true })
  await p.getByRole('button', { name: 'Entrar a la demo con datos ficticios' }).click()
  await p.getByRole('heading', { name: 'Lista del día' }).waitFor()
  await p.screenshot({ path: `${S}/v-${tema}-hoy.png`, fullPage: true })
  await p.getByRole('button', { name: /^Abrir reserva/ }).first().click()
  await p.waitForTimeout(300)
  await p.screenshot({ path: `${S}/v-${tema}-reserva.png`, fullPage: true })
  await p.goto('http://localhost:4181/#/primeros-pasos'); await p.waitForTimeout(300)
  await p.screenshot({ path: `${S}/v-${tema}-asistente.png`, fullPage: true })
  await p.goto('http://localhost:4181/#/ajustes'); await p.waitForTimeout(300)
  await p.screenshot({ path: `${S}/v-${tema}-ajustes.png`, fullPage: true })
  await ctx.close()
}
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } })
const p = await ctx.newPage()
await p.goto('http://localhost:4181/')
await p.getByRole('button', { name: 'Entrar a la demo con datos ficticios' }).click()
await p.getByRole('heading', { name: 'Lista del día' }).waitFor()
await p.screenshot({ path: `${S}/v-desk-hoy.png`, fullPage: true })
await b.close()
